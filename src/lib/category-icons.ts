const REGISTRY: IconSet = Object.assign({}, ...ICON_GROUPS.map((g) => g.icons)) as IconSet;

export const ICON_NAMES: string[] = Object.keys(REGISTRY);

/** Unknown names resolve to a plain dot: a bad row must not break a render. */
export function iconFor(name: string): LucideIcon {
  return REGISTRY[name] ?? Circle;
}
